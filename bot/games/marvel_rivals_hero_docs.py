DEADPOOL_VARIANTS: dict[str, set[str]] = {
    "Deadpool (Vanguard)": {"0", "1", "2"},
    "Deadpool (Duelist)": {"3", "4", "5"},
    "Deadpool (Strategist)": {"6", "7", "8"},
}


def resolve_hero_name(hero: str) -> str:
    """Map picker labels to official documentation labels."""
    return HERO_ALIASES.get(hero, hero)


def _variant_actions(hero: str, actions: list[dict[str, str]]) -> list[dict[str, str]]:
    variants = DEADPOOL_VARIANTS.get(hero)
    if not variants:
        return actions
    return [a for a in actions if a.get("variant") in variants]


def get_hero_actions(hero: str) -> list[dict[str, str]]:
    """Return the action reference for a hero, or an empty list if missing."""
    official_name = resolve_hero_name(hero)
    actions = list(HERO_ACTIONS.get(official_name, {}).get("actions", []))
    return _variant_actions(hero, actions)


